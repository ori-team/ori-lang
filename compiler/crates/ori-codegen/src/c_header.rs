#[cfg(test)]
mod tests {
    use super::{c_identifier, header_guard, pascal_case_identifier};

    #[test]
    fn converts_ori_names_to_portable_c_identifiers() {
        assert_eq!(pascal_case_identifier("point_data"), "PointData");
        assert_eq!(c_identifier("switch"), "switch_");
        assert_eq!(c_identifier("score-value"), "score_value");
        assert_eq!(
            header_guard("libscore-api.h"),
            "ORI_LIBSCORE_API_H_INCLUDED"
        );
    }
}
